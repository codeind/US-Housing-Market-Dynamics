"""Build dashboard/dashboard_data.js from the project's data files.

Run from the repository root:
    python dashboard/build_data.py
"""
import json
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
df = pd.read_csv(ROOT / "data" / "reshaped_zillow.csv")
df["Date"] = pd.to_datetime(df["Date"])
clusters = pd.read_csv(ROOT / "data" / "clustered_metro_housing.csv").set_index("RegionName")

wide = df.pivot_table(index="RegionName", columns="Date", values="ZHVI").sort_index()
dates = list(wide.columns)
last = dates[-1]
march_2020 = pd.Timestamp("2020-03-31")
year_ago = dates[-13]
ten_years_ago = dates[-121]
meta = df.drop_duplicates("RegionName").set_index("RegionName")[["State", "SizeRank"]]


def pct(a, b):
    return None if (pd.isna(a) or pd.isna(b) or b == 0) else round((a / b - 1) * 100, 2)


metros = []
for name, row in wide.iterrows():
    first_valid = int(np.argmax(row.notna().values))
    vals = row.values[first_valid:]
    cagr10 = None
    if not (pd.isna(row[last]) or pd.isna(row[ten_years_ago])):
        cagr10 = round(((row[last] / row[ten_years_ago]) ** (1 / 10) - 1) * 100, 2)
    metros.append({
        "n": name,
        "s": meta.loc[name, "State"],
        "r": int(meta.loc[name, "SizeRank"]),
        "o": first_valid,                                   # index of the first month with data
        "v": [None if pd.isna(x) else int(round(x)) for x in vals],
        "latest": None if pd.isna(row[last]) else int(round(row[last])),
        "yoy": pct(row[last], row[year_ago]),
        "cagr10": cagr10,
        "covid": pct(row[last], row[march_2020]),
        "vol": int(round(row.std())),
        "c": int(clusters.loc[name, "Cluster"]) if name in clusters.index else None,
    })

# seasonality: each month's value relative to its centred 13-month average, averaged by calendar month
s = df.dropna(subset=["ZHVI"]).sort_values(["RegionName", "Date"]).copy()
s["trend"] = s.groupby("RegionName")["ZHVI"].transform(lambda x: x.rolling(13, center=True).mean())
seasonal = (s["ZHVI"] / s["trend"] * 100 - 100).groupby(s["Date"].dt.month).mean().round(3).tolist()

latest_rows = df[df["Date"] == last]
states = (latest_rows.groupby("State")["ZHVI"].median().round().astype(int)
          .sort_values(ascending=False).reset_index().values.tolist())

national = wide.median(axis=0)
covid_all = [m["covid"] for m in metros if m["covid"] is not None]

cl = clusters.groupby("Cluster").agg(
    metros=("Post_COVID_Growth", "size"),
    growth=("Post_COVID_Growth", "median"),
    volatility=("Volatility", "median"),
    avg=("Avg_ZHVI", "median"),
)
cluster_profiles = [
    {"c": int(k), "metros": int(r.metros), "growth": round(r.growth * 100, 1),
     "volatility": int(round(r.volatility)), "avg": int(round(r.avg))}
    for k, r in cl.iterrows()
]

data = {
    "dates": [d.strftime("%Y-%m") for d in dates],
    "latest": last.strftime("%b %Y"),
    "metros": metros,
    "national": [int(round(x)) for x in national.values],
    "seasonal": seasonal,
    "states": states,
    "clusters": cluster_profiles,
    "summary": {
        "metros": len(metros),
        "median_latest": int(round(latest_rows["ZHVI"].median())),
        "median_covid": round(float(np.median(covid_all)), 1),
        "metros_with_covid": len(covid_all),
    },
}
out = Path(__file__).with_name("dashboard_data.js")
out.write_text("// Generated by dashboard/build_data.py from data/ - do not edit by hand.\n"
               "window.HOUSING = " + json.dumps(data, separators=(",", ":")) + ";\n")
print(f"wrote {out.name}: {out.stat().st_size/1e6:.2f} MB, {len(metros)} metros, latest {data['latest']}")
print("summary:", data["summary"])
